const assert=require('node:assert/strict');
const {run}=require('../backtest/engine.cjs');
const bars=Array.from({length:40},(_,i)=>({t:i*60000,o:100,h:101,l:99,c:100,v:100,confirmed:true}));
let seen=[];
const signal=history=>{seen.push(history.at(-1).t);return {direction:'up',stop:95,target:110}};
const same=bars.map(b=>({...b}));same[36].h=112;same[36].l=94;
const r=run(same,{warmup:35,interval:60000,fee:.001,slippage:0,maxHold:1},signal);
assert.equal(r.trades[0].signalTime,35*60000);assert.equal(r.trades[0].entryTime,36*60000);
assert.equal(r.trades[0].exit,95);assert.equal(r.ambiguous,1);assert(r.trades[0].net<r.trades[0].gross);assert(Math.abs(r.summary.finalCapital-(10000+r.trades.reduce((sum,t)=>sum+t.net,0)))<1e-8);
assert.deepEqual(seen,[35,36,37,38].map(i=>i*60000));
const incomplete=[...bars,{t:40*60000,o:100,h:101,l:99,c:100,confirmed:false}];
assert.equal(run(incomplete,{warmup:35,interval:60000},()=>null).bars,40);
const gap=bars.map(b=>({...b}));gap[37].t+=60000;gap[38].t+=60000;gap[39].t+=60000;
const g=run(gap,{warmup:35,interval:60000,fee:0,slippage:0},signal);
assert.equal(g.gaps,1);assert.equal(g.trades[0].reason,'数据缺口前平仓');assert.equal(g.trades.length,1);
const short=run(same,{warmup:35,interval:60000,fee:0,slippage:0,maxHold:1},()=>({direction:'down',stop:105,target:90}));
assert.equal(short.trades[0].exit,105);assert(short.trades[0].net<0);
assert.throws(()=>run(bars,{risk:.2}),/范围/);
console.log('Backtest PASS: next-bar execution, causal signal time, conservative stop priority, long/short P&L, fees, incomplete bars and gap reset');
